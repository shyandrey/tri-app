import { execFileSync } from 'node:child_process'
import fs from 'node:fs/promises'
import { parseChangelog } from './release-notes.mjs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export function resolveBuildMetadata(version, env = process.env, readCommit = () => execFileSync('git', ['rev-parse', 'HEAD'], {encoding:'utf8',stdio:['ignore','pipe','ignore']}).trim()) {
  const validCommit = value => typeof value === 'string' && /^[a-f0-9]{40}$/i.test(value.trim())
  let commit = [env.BUILD_COMMIT, env.CF_WORKERS_BUILD_COMMIT, env.CF_PAGES_COMMIT_SHA, env.GITHUB_SHA].find(validCommit)
  if (!commit) { try { const git = readCommit(); if (validCommit(git)) commit = git } catch { /* Source archives/local dev can lack Git. */ } }
  return {version, commit: commit?.trim().toLowerCase() ?? 'unknown'}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const {version} = JSON.parse(await fs.readFile('package.json', 'utf8'))
  const metadata = resolveBuildMetadata(version)
  const release = parseChangelog(await fs.readFile('CHANGELOG.md', 'utf8'), version)
  await fs.mkdir('.generated', {recursive:true})
  await fs.writeFile('.generated/build-metadata.ts', `// Generated by scripts/build-metadata.mjs; public values only.\nexport const buildMetadata = ${JSON.stringify(metadata)} as const\n`)
  await fs.writeFile('.generated/current-release.ts', `// Generated from CHANGELOG.md; current release only.\nexport const currentRelease = ${JSON.stringify(release)} as const\n`)
  console.log(`Build metadata: ${metadata.version} / ${metadata.commit}`)
}
