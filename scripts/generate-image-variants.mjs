// Local asset derivatives only. Originals and athlete identity/photo registries are untouched.
// Uses sharp already supplied by the existing Wrangler toolchain; no dependency installation.
import sharp from 'sharp'
import fs from 'node:fs/promises'
import path from 'node:path'
const root='src/assets/optimized'
await fs.mkdir(root,{recursive:true});await fs.mkdir('src/generated',{recursive:true})
const inventory=[]
async function variant(source,group,width,options={quality:88,alphaQuality:100,effort:4}){
 const name=path.parse(source).name,dest=`${root}/${group}/${name}-${width}.webp`
 await fs.mkdir(path.dirname(dest),{recursive:true})
 const info=await sharp(source).resize({width,withoutEnlargement:true}).webp(options).toFile(dest)
 inventory.push({source,file:dest,width:info.width,height:info.height,bytes:info.size,format:'webp'})
 return {file:dest,width:info.width,height:info.height}
}
const showcase={}
for(const rel of (await fs.readdir('src/assets/showcase',{recursive:true})).filter(f=>f.endsWith('.png')).sort()){
 const source='src/assets/showcase/'+rel;showcase[path.parse(source).name]=await Promise.all([640,1280,1672].map(w=>variant(source,'showcase',w)))
}
const photos=(await fs.readdir('public/athletes')).filter(f=>/\.(png|jpe?g)$/i.test(f)).sort().map(f=>['/athletes/'+f,'public/athletes/'+f])
photos.push(['blummenfeltOriginal','src/assets/athletes/blummenfelt.jpg'])
const athletes={}
// Bounded processing keeps generation predictable on laptops.
for(let i=0;i<photos.length;i+=4)await Promise.all(photos.slice(i,i+4).map(async([key,source])=>{athletes[key]=await Promise.all([180,396].map(w=>variant(source,'athletes',w)))}))
for(const file of ['ironman-pro','t100-worldtour']){
 const source=`src/assets/series/${file}.jpeg`,dest=`${root}/series/${file}-216.png`;await fs.mkdir(path.dirname(dest),{recursive:true})
 const info=await sharp(source).resize({width:216,withoutEnlargement:true}).png({compressionLevel:9}).toFile(dest)
 inventory.push({source,file:dest,width:info.width,height:info.height,bytes:info.size,format:'png'})
}
async function manifest(file,entries,athlete=false){
 let code='// Generated by scripts/generate-image-variants.mjs. Do not edit by hand.\n'
 if(athlete)code+="import blummenfeltOriginal from '../assets/athletes/blummenfelt.jpg'\n"
 const rows=[];let n=0
 for(const key of Object.keys(entries).sort()){
  const variants=[];for(const v of entries[key]){const id='image'+n++;code+=`import ${id} from '${path.relative('src/generated',v.file)}?no-inline'\n`;variants.push(`{ src: ${id}, width: ${v.width}, height: ${v.height} }`)}
  rows.push(`  ${key==='blummenfeltOriginal'?'[blummenfeltOriginal]':JSON.stringify(key)}: [${variants.join(', ')}],`)
 }
 code+='\nexport const imageVariants: Record<string, { src: string; width: number; height: number }[]> = {\n'+rows.join('\n')+'\n}\n'
 await fs.writeFile(file,code)
}
await manifest('src/generated/showcaseImageVariants.ts',showcase)
await manifest('src/generated/athleteImageVariants.ts',athletes,true)
inventory.sort((a,b)=>a.file.localeCompare(b.file))
await fs.writeFile('src/generated/image-variants.json',JSON.stringify(inventory,null,2)+'\n')
console.log(`Generated ${inventory.length} derivatives (${inventory.reduce((n,r)=>n+r.bytes,0)} bytes); originals retained.`)
