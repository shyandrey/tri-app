import fs from 'node:fs/promises'
import path from 'node:path'
import os from 'node:os'
import { sha256, auditPhotoFiles, slugify } from './athlete-photo-core.mjs'
import { STAGING, REGISTRY, EVIDENCE, stagingBase, safePath, atomicJson, validateBytes, inspectProduction, compareImages } from './athlete-photo-staging.mjs'

const findingHash = findings => sha256(Buffer.from(JSON.stringify(findings)))
function acceptsWeakSimilarity(entry, review) {
  const resolution = review.similarityReview
  return resolution?.decision === 'ACCEPT_WEAK_SIMILARITY' && resolution.reviewedSha256 === entry.sha256 && resolution.findingsSha256 === findingHash(entry.duplicateFindings ?? []) && Boolean(resolution.reason?.trim()) && (entry.duplicateFindings ?? []).every(f => f.kind === 'POSSIBLE_VISUAL_MATCH')
}

const registryText = registry => '// Generated by scripts/import-athlete-photos.mjs.\n// Keep this file in git so the app has a stable photo registry after imports.\nexport const athletePhotosByName: Record<string, string> = {\n'+Object.entries(registry).sort(([a],[b])=>a.localeCompare(b)).map(([n,p])=>`  ${JSON.stringify(n)}: ${JSON.stringify(p)},`).join('\n')+'\n}\n'
export async function publishApproved({root,manifest,reviews,registry,athletes,decoder,injectFailure=()=>{}}) {
  if(manifest.complete!==true)throw new Error('Incomplete staging batch')
  const relativeBase=stagingBase(manifest.batchId ?? null)
  if(manifest.batchId && reviews.batchId!==manifest.batchId)throw new Error('Review batch identity mismatch')
  const registryBefore=await fs.readFile(await safePath(root,REGISTRY))
  // Every supplied row must be APPROVED. Omitted rows cannot be published.
  if(reviews.manifestSha256!==sha256(Buffer.from(JSON.stringify(manifest))) || !reviews.entries?.length)throw new Error('Review manifest binding required')
  const beforeAudit=await auditPhotoFiles(root,registry);if(beforeAudit.issues.length)throw new Error('Production preflight failed')
  const existingProduction=await inspectProduction(root,registry,decoder)
  const ids=new Set(), plans=[]
  for(const review of reviews.entries){
    const e=manifest.entries.find(e=>e.athlete.athleteId===review.athleteId)
    if(!e||e.reviewStatus!=='APPROVED'||review.reviewStatus!=='APPROVED')throw new Error('Publish requires APPROVED; pending/rejected/review-required refused')
    if(ids.has(review.athleteId))throw new Error('Duplicate review');ids.add(review.athleteId)
    if(!review.reviewer?.trim() || !Number.isFinite(Date.parse(review.reviewedAt)) || review.sha256!==e.sha256 || review.sourceImageUrl!==e.sourceImageUrl || review.reviewMethod!=='manual-visual-review' || review.verifiedProfileUrl!==e.verifiedProfileUrl || JSON.stringify(review.athlete)!==JSON.stringify(e.athlete))throw new Error('Explicit byte-bound manual review required')
    const athlete=athletes.find(a=>a.id===e.athlete.athleteId && a.nameEn===e.athlete.nameEn && a.gender===e.athlete.gender)
    const weakResolved = acceptsWeakSimilarity(e, review)
    if(!athlete || e.discoveryConfidence!=='HIGH' || !['VALIDATED','VALIDATED_AFTER_MANUAL_REVIEW'].includes(e.validationStatus) || (e.duplicateFindings?.length && !weakResolved))throw new Error('Unvalidated athlete/image or unresolved similarity findings')
    if((athlete.image||registry[athlete.nameEn]) && !(review.refresh===true&&review.replace===true))throw new Error('Existing/manual photo protected')
    if(!e.localStagingPath.startsWith(`${relativeBase}/${athlete.id}/`))throw new Error('Not an athlete staging path')
    const file=await safePath(root,e.localStagingPath),bytes=await fs.readFile(file)
    if(sha256(bytes)!==e.sha256 || bytes.length!==e.byteSize)throw new Error('Staged bytes changed')
    const ext=validateBytes(bytes,e.contentType),[decoded]=await decoder.inspect([file])
    if(decoded.error||decoded.width!==e.width||decoded.height!==e.height||decoded.pixelSha256!==e.pixelSha256||decoded.dHash!==e.dHash)throw new Error('Staged decode changed')
    const target='/athletes/'+slugify(athlete.nameEn)+'.'+ext
    if(Object.entries(registry).some(([n,p])=>p===target&&n!==athlete.nameEn))throw new Error('Production path collision')
    plans.push({entry:e,review,bytes,target,old:registry[athlete.nameEn]})
  }
  const collisions=compareImages(plans.map(p=>p.entry),existingProduction).filter(m=>m.scope!=='production'||!plans.some(p=>p.entry.athlete.athleteId===m.athleteId && p.entry.athlete.nameEn===m.otherAthlete.nameEn))
  for(const collision of collisions) {
    const plan = plans.find(p => p.entry.athlete.athleteId === collision.athleteId)
    const previouslyReviewed = plan.entry.duplicateFindings?.some(f => findingHash(f) === findingHash(collision))
    if(collision.kind !== 'POSSIBLE_VISUAL_MATCH' || !previouslyReviewed || !acceptsWeakSimilarity(plan.entry, plan.review))throw new Error('Duplicate/new similar image requires resolution before publish')
  }
  if(new Set(plans.map(p=>p.target)).size!==plans.length)throw new Error('Duplicate planned path')
  const projected={...registry};for(const p of plans)projected[p.entry.athlete.nameEn]=p.target
  const temp=await fs.mkdtemp(path.join(os.tmpdir(),'tri-photo-preflight-'))
  try {
    await fs.cp(path.join(root,'public/athletes'),path.join(temp,'public/athletes'),{recursive:true})
    for(const p of plans){if(p.old&&p.old!==p.target)await fs.unlink(path.join(temp,'public'+p.old));await fs.writeFile(path.join(temp,'public'+p.target),p.bytes)}
    const audit=await auditPhotoFiles(temp,projected);if(audit.issues.length)throw new Error('Projected photo audit failed: '+audit.issues.join('; '))
  } finally {await fs.rm(temp,{recursive:true,force:true})}
  // A persistent journal allows deliberate recovery after an interrupted process.
  const staging=await safePath(root,STAGING)
  const lock=await fs.open(path.join(staging,'.download.lock'),'wx')
  const transaction=path.join(staging,'.publish-transaction')
  let started=false
  try {
    await fs.mkdir(transaction);started=true
    const paths=[...new Set([REGISTRY,EVIDENCE,...plans.flatMap(p=>['public'+p.target,...(p.old?['public'+p.old]:[])])])]
    const journal=[]
    for(const [i,relative]of paths.entries()){
      const full=await safePath(root,relative)
      const bytes=await fs.readFile(full).catch(e=>{if(e.code==='ENOENT')return null;throw e})
      if(bytes)await fs.writeFile(path.join(transaction,`${i}.bak`),bytes)
      journal.push({relative,backup:bytes?`${i}.bak`:null})
    }
    await atomicJson(path.join(transaction,'journal.json'),journal)
    // Recheck production snapshot after preflight, before the first production write.
    for(const original of existingProduction)if(sha256(await fs.readFile(await safePath(root,'public'+original.path)))!==original.sha256)throw new Error('Production changed during preflight')
    if(!registryBefore.equals(await fs.readFile(await safePath(root,REGISTRY))))throw new Error('Registry changed during preflight')
    const evidence=await fs.readFile(await safePath(root,EVIDENCE),'utf8').then(JSON.parse).catch(e=>{if(e.code==='ENOENT')return {schemaVersion:1,entries:{}};throw e})
    for(const p of plans){
      await fs.writeFile(await safePath(root,'public'+p.target),p.bytes)
      if(p.old&&p.old!==p.target)await fs.unlink(await safePath(root,'public'+p.old))
      evidence.entries[p.entry.athlete.athleteId]={...p.entry,...(manifest.batchId?{batchId:manifest.batchId}:{}),localPath:p.target,confidence:p.entry.discoveryConfidence,reviewedAt:p.review.reviewedAt,reviewMethod:p.review.reviewMethod,reviewedSha256:p.review.sha256,publishedSha256:sha256(p.bytes),review:p.review,publishedAt:new Date().toISOString()}
    }
    await injectFailure('after-files')
    await fs.writeFile(await safePath(root,REGISTRY),registryText(projected))
    await atomicJson(await safePath(root,EVIDENCE),evidence)
    await injectFailure('after-registry')
    for(const p of plans)if(sha256(await fs.readFile(await safePath(root,'public'+p.target)))!==p.entry.sha256)throw new Error('Published byte verification failed')
    const audit=await auditPhotoFiles(root,projected);if(audit.issues.length)throw new Error('Post-publish photo audit failed')
    await fs.rm(transaction,{recursive:true})
    return {published:plans.length,audit}
  } catch(error){
    if(started){
      const journal=await fs.readFile(path.join(transaction,'journal.json'),'utf8').then(JSON.parse).catch(e=>{if(e.code==='ENOENT')return null;throw e})
      if(journal)for(const row of journal){const target=await safePath(root,row.relative);if(row.backup)await fs.writeFile(target,await fs.readFile(path.join(transaction,row.backup)));else await fs.rm(target,{force:true})}
      await fs.rm(transaction,{recursive:true})
    }
    throw error
  } finally {await lock.close();await fs.unlink(path.join(staging,'.download.lock'))}
}
